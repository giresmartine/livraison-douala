function isWithinRing(longitude: number, latitude: number, ring: BoundaryRing) {
  let inside = false;

  for (let index = 0, previous = ring.length - 1; index < ring.length; previous = index++) {
    const [previousLongitude, previousLatitude] = ring[previous];
    const [currentLongitude, currentLatitude] = ring[index];
    const cross =
      (longitude - previousLongitude) * (currentLatitude - previousLatitude) -
      (latitude - previousLatitude) * (currentLongitude - previousLongitude);

    if (
      Math.abs(cross) < 1e-10 &&
      longitude >= Math.min(previousLongitude, currentLongitude) - 1e-10 &&
      longitude <= Math.max(previousLongitude, currentLongitude) + 1e-10 &&
      latitude >= Math.min(previousLatitude, currentLatitude) - 1e-10 &&
      latitude <= Math.max(previousLatitude, currentLatitude) + 1e-10
    ) {
      return true;
    }

    if (
      (previousLatitude > latitude) !== (currentLatitude > latitude) &&
      longitude <
        ((currentLongitude - previousLongitude) * (latitude - previousLatitude)) /
          (currentLatitude - previousLatitude) +
          previousLongitude
    ) {
      inside = !inside;
    }
  }

  return inside;
}

function distanceToSegmentKm(
  longitude: number,
  latitude: number,
  start: readonly number[],
  end: readonly number[],
) {
  const kilometersPerDegree = (Math.PI * EARTH_RADIUS_KM) / 180;
  const longitudeScale = kilometersPerDegree * Math.cos((latitude * Math.PI) / 180);
  const startX = (start[0] - longitude) * longitudeScale;
  const startY = (start[1] - latitude) * kilometersPerDegree;
  const endX = (end[0] - longitude) * longitudeScale;
  const endY = (end[1] - latitude) * kilometersPerDegree;
  const segmentX = endX - startX;
  const segmentY = endY - startY;
  const lengthSquared = segmentX * segmentX + segmentY * segmentY;
  const projection = lengthSquared === 0
    ? 0
    : Math.max(0, Math.min(1, -(startX * segmentX + startY * segmentY) / lengthSquared));

  return Math.hypot(startX + projection * segmentX, startY + projection * segmentY);
}

function isWithinDoualaBoundary({ latitude, longitude }: Coordinates) {
  return boundaryPolygons.some((polygon) => {
    const [outerRing, ...holes] = polygon;
    return Boolean(
      outerRing &&
        isWithinRing(longitude, latitude, outerRing) &&
        !holes.some((hole) => isWithinRing(longitude, latitude, hole)),
    );
  });
}

function distanceToDoualaBoundaryKm({ latitude, longitude }: Coordinates) {
  let closestDistance = Number.POSITIVE_INFINITY;

  for (const polygon of boundaryPolygons) {
    for (const ring of polygon) {
      for (let index = 0, previous = ring.length - 1; index < ring.length; previous = index++) {
        closestDistance = Math.min(
          closestDistance,
          distanceToSegmentKm(longitude, latitude, ring[previous], ring[index]),
        );
      }
    }
  }

  return closestDistance;
}

export type DeliveryAddress = {
  city: string;
  neighborhood: string;
  landmark: string;
  coordinates?: Coordinates;
};

export type DeliveryAddressValidation =
  | { accepted: true }
  | { accepted: false; reason: "outside-city" | "incomplete" };

export function isWithinDoualaCoverage({ latitude, longitude }: Coordinates) {
  if (!Number.isFinite(latitude) || !Number.isFinite(longitude)) return false;
  return isWithinDoualaBoundary({ latitude, longitude }) ||
    distanceToDoualaBoundaryKm({ latitude, longitude }) <= DOUALA_COVERAGE_BUFFER_KM;
}

export function isClearlyFarFromDouala({ latitude, longitude }: Coordinates) {
  if (!Number.isFinite(latitude) || !Number.isFinite(longitude)) return false;

  const toRadians = (degrees: number) => (degrees * Math.PI) / 180;
  const latitudeDelta = toRadians(latitude - doualaReferencePoint.latitude);
  const longitudeDelta = toRadians(longitude - doualaReferencePoint.longitude);
  const haversine =
    Math.sin(latitudeDelta / 2) ** 2 +
    Math.cos(toRadians(doualaReferencePoint.latitude)) *
      Math.cos(toRadians(latitude)) *
      Math.sin(longitudeDelta / 2) ** 2;
  const distanceKm =
    2 * EARTH_RADIUS_KM * Math.atan2(Math.sqrt(haversine), Math.sqrt(1 - haversine));

  return distanceKm >= DOUALA_FAR_DISTANCE_KM;
}

export function validateDeliveryAddress(
  address: DeliveryAddress,
): DeliveryAddressValidation {
  if (address.city.trim().toLocaleLowerCase() !== doualaCoverage.city.toLocaleLowerCase()) {
    return { accepted: false, reason: "outside-city" };
  }

  if (!address.neighborhood.trim() || !address.landmark.trim()) {
    return { accepted: false, reason: "incomplete" };
  }

  return { accepted: true };
}
